import Foundation

/// Система самодіагностики старого авто (до OBD2), яка показує коди миганням лампи.
public struct RetroSystem: Identifiable, Sendable {
    public struct Code: Sendable {
        public let code: String
        public let title: String
        public let details: String
        public let causes: [String]
        public let severity: Int
        /// Код означає «несправностей немає» або «кінець виводу».
        public let isInfo: Bool
    }

    public let id: String
    public let title: String
    public let cars: String
    public let years: String
    /// Скільки цифр у коді (2 або 4); 0 — довільна кількість.
    public let digits: Int
    public let connector: String
    public let steps: [String]
    public let howToRead: String
    public let warning: String?
    public let notes: String?
    public let codes: [Code]

    public func lookup(_ raw: String) -> Code? {
        let c = raw.filter(\.isNumber)
        return codes.first { $0.code == c }
    }
}

private func code(_ c: String, _ t: String, _ d: String, _ r: [String], _ s: Int = 2, info: Bool = false) -> RetroSystem.Code {
    .init(code: c, title: t, details: d, causes: r, severity: s, isInfo: info)
}

